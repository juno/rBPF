module Rbpf
  # linux/filter.h (classic BPF) と同じ値
  module Op
    # instruction class
    LD = 0x00; LDX = 0x01; ST = 0x02; STX = 0x03
    ALU = 0x04; JMP = 0x05; RET = 0x06; MISC = 0x07
    # ld/ldx size
    W = 0x00; H = 0x08; B = 0x10
    # ld/ldx mode
    IMM = 0x00; ABS = 0x20; IND = 0x40; MEM = 0x60; LEN = 0x80; MSH = 0xa0
    # alu/jmp source
    K = 0x00; X = 0x08
    # alu op
    ADD = 0x00; SUB = 0x10; MUL = 0x20; DIV = 0x30; OR = 0x40
    AND = 0x50; LSH = 0x60; RSH = 0x70; NEG = 0x80; MOD = 0x90; XOR = 0xa0
    # jmp op
    JA = 0x00; JEQ = 0x10; JGT = 0x20; JGE = 0x30; JSET = 0x40
    # ret value source
    RET_K = 0x00; RET_A = 0x10
    # misc op
    TAX = 0x00; TXA = 0x80
  end
end
